#!/usr/bin/env python3
"""
x11vnc SSH+SSL viewer launcher for Windows.

Chain:
  VNC viewer --plain--> 127.0.0.1:LPORT (this app)
      --TLS--> [SSH tunnel: direct-tcpip] --> 127.0.0.1:5900 on server (x11vnc -ssl)

x11vnc's "-ssl" wraps the *whole* VNC connection in TLS, which ordinary Windows
viewers (TigerVNC, TightVNC, RealVNC, UltraVNC) cannot speak. This app does the
SSH tunnel and the TLS layer itself, then starts any normal viewer against a
plain local port.

Security:
  * SSH host key: trust-on-first-use (confirmed by you), stored in known_hosts
  * x11vnc certificate (self-generated by SAVE_NOPROMPT): SHA-256 fingerprint
    pinned on first use; a changed certificate is refused
  * local listener binds to 127.0.0.1 only

Requires: Python 3.9+, `pip install paramiko`
Build exe: pip install pyinstaller && pyinstaller --onefile --noconsole x11vnc_viewer.py
"""
import base64
import hashlib
import json
import os
import socket
import ssl
import subprocess
import threading
import tkinter as tk
from tkinter import filedialog, messagebox, ttk

import paramiko

APP_DIR = os.path.join(os.environ.get("APPDATA", os.path.expanduser("~")), "x11vnc-viewer")
os.makedirs(APP_DIR, exist_ok=True)
CFG_FILE = os.path.join(APP_DIR, "config.json")
CERT_FILE = os.path.join(APP_DIR, "known_certs.json")
HOSTS_FILE = os.path.join(APP_DIR, "known_hosts")

VIEWER_CANDIDATES = [
    r"C:\Program Files\TigerVNC\vncviewer.exe",
    r"C:\Program Files (x86)\TigerVNC\vncviewer.exe",
    r"C:\Program Files\TightVNC\tvnviewer.exe",
    r"C:\Program Files\uvnc bvba\UltraVNC\vncviewer.exe",
    r"C:\Program Files\RealVNC\VNC Viewer\vncviewer.exe",
]


def load_json(path, default):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def save_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def pipe(src, dst, done):
    try:
        while True:
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)
    except Exception:
        pass
    finally:
        done.set()


def bridge(a, b):
    """Bidirectional copy between two socket-like objects until either side closes."""
    done = threading.Event()
    threading.Thread(target=pipe, args=(a, b, done), daemon=True).start()
    threading.Thread(target=pipe, args=(b, a, done), daemon=True).start()
    done.wait()
    for s in (a, b):
        try:
            s.close()
        except Exception:
            pass


class TofuPolicy(paramiko.MissingHostKeyPolicy):
    def __init__(self, confirm):
        self.confirm = confirm

    def missing_host_key(self, client, hostname, key):
        fp = base64.b64encode(hashlib.sha256(key.asbytes()).digest()).decode().rstrip("=")
        if not self.confirm(f"Unknown SSH host key for {hostname}\n\n"
                            f"{key.get_name()}  SHA256:{fp}\n\nTrust this host?"):
            raise paramiko.SSHException("SSH host key rejected")
        client.get_host_keys().add(hostname, key.get_name(), key)
        client.save_host_keys(HOSTS_FILE)


class Tunnel:
    def __init__(self, log, confirm):
        self.log, self.confirm = log, confirm
        self.client = None
        self.listener = None
        self.stopped = threading.Event()
        self.pin_key = ""
        self.ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        self.ctx.check_hostname = False
        self.ctx.verify_mode = ssl.CERT_NONE  # we pin the fingerprint ourselves

    # ---- SSH -------------------------------------------------------------
    def connect_ssh(self, host, port, user, password, keyfile, passphrase):
        c = paramiko.SSHClient()
        if os.path.exists(HOSTS_FILE):
            c.load_host_keys(HOSTS_FILE)
        c.set_missing_host_key_policy(TofuPolicy(self.confirm))
        self.log(f"SSH: connecting to {host}:{port} as {user} ...")
        c.connect(host, port=port, username=user,
                  password=password or None,
                  key_filename=keyfile or None,
                  passphrase=passphrase or None,
                  allow_agent=True, look_for_keys=True, timeout=15)
        c.get_transport().set_keepalive(30)
        self.client = c
        self.log("SSH: connected.")

    def open_channel(self, rport):
        return self.client.get_transport().open_channel(
            "direct-tcpip", ("127.0.0.1", rport), ("127.0.0.1", 0))

    # ---- TLS -------------------------------------------------------------
    def tls_over_channel(self, rport):
        chan = self.open_channel(rport)
        a, b = socket.socketpair()
        done = threading.Event()
        threading.Thread(target=pipe, args=(chan, a, done), daemon=True).start()
        threading.Thread(target=pipe, args=(a, chan, done), daemon=True).start()
        try:
            b.settimeout(15)
            tls = self.ctx.wrap_socket(b)
            tls.settimeout(None)
        except Exception:
            chan.close(); a.close(); b.close()
            raise
        return tls

    def verify_cert(self, tls, first_use_ok):
        der = tls.getpeercert(binary_form=True)
        fp = hashlib.sha256(der).hexdigest()
        store = load_json(CERT_FILE, {})
        old = store.get(self.pin_key)
        if old is None:
            if not first_use_ok:
                raise ssl.SSLError("unknown server certificate")
            pretty = ":".join(fp[i:i + 2] for i in range(0, len(fp), 2))
            if not self.confirm(f"x11vnc certificate for {self.pin_key}\n\nSHA-256:\n{pretty}\n\n"
                                f"Trust and remember it?"):
                raise ssl.SSLError("certificate rejected")
            store[self.pin_key] = fp
            save_json(CERT_FILE, store)
        elif old != fp:
            raise ssl.SSLError("x11vnc certificate CHANGED since last time - refusing "
                               "(delete it from known_certs.json if you regenerated it)")

    def probe(self, rport):
        """Handshake once so cert trust prompts happen before the viewer starts."""
        self.log("TLS: probing x11vnc certificate ...")
        tls = self.tls_over_channel(rport)
        try:
            self.verify_cert(tls, first_use_ok=True)
            self.log(f"TLS: OK ({tls.version()})")
        finally:
            tls.close()

    # ---- local proxy -----------------------------------------------------
    def start_proxy(self, rport, lport):
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.bind(("127.0.0.1", lport))
        s.listen(5)
        self.listener = s
        threading.Thread(target=self._accept, args=(rport,), daemon=True).start()
        return s.getsockname()[1]

    def _accept(self, rport):
        while not self.stopped.is_set():
            try:
                conn, _ = self.listener.accept()
            except Exception:
                break
            threading.Thread(target=self._handle, args=(conn, rport), daemon=True).start()

    def _handle(self, conn, rport):
        try:
            tls = self.tls_over_channel(rport)
            self.verify_cert(tls, first_use_ok=False)
        except Exception as e:
            self.log(f"Connection refused: {e}")
            conn.close()
            return
        self.log("Viewer connected.")
        bridge(conn, tls)
        self.log("Viewer disconnected.")

    def stop(self):
        self.stopped.set()
        for obj in (self.listener, self.client):
            try:
                if obj:
                    obj.close()
            except Exception:
                pass


class App:
    def __init__(self, root):
        self.root = root
        root.title("x11vnc SSH+SSL Viewer")
        cfg = load_json(CFG_FILE, {})
        self.tunnel = None
        self.viewer_proc = None

        default_viewer = next((p for p in VIEWER_CANDIDATES if os.path.exists(p)), "")
        self.vars = {
            "host": tk.StringVar(value=cfg.get("host", "")),
            "port": tk.StringVar(value=cfg.get("port", "22")),
            "user": tk.StringVar(value=cfg.get("user", "")),
            "password": tk.StringVar(),
            "keyfile": tk.StringVar(value=cfg.get("keyfile", "")),
            "rport": tk.StringVar(value=cfg.get("rport", "5900")),
            "lport": tk.StringVar(value=cfg.get("lport", "0")),
            "viewer": tk.StringVar(value=cfg.get("viewer", default_viewer)),
            "args": tk.StringVar(value=cfg.get("args", "127.0.0.1::{port}")),
        }
        f = ttk.Frame(root, padding=10)
        f.grid(sticky="nsew")
        root.columnconfigure(0, weight=1)
        root.rowconfigure(0, weight=1)
        f.columnconfigure(1, weight=1)

        rows = [
            ("SSH host", "host", False), ("SSH port", "port", False),
            ("SSH user", "user", False), ("SSH password / key passphrase", "password", True),
            ("SSH key file (optional)", "keyfile", False),
            ("x11vnc port on server", "rport", False),
            ("Local port (0 = auto)", "lport", False),
            ("VNC viewer exe", "viewer", False),
            ("Viewer arguments", "args", False),
        ]
        for i, (label, key, secret) in enumerate(rows):
            ttk.Label(f, text=label).grid(row=i, column=0, sticky="w", pady=2)
            ttk.Entry(f, textvariable=self.vars[key], show="*" if secret else "",
                      width=42).grid(row=i, column=1, sticky="ew", pady=2)
        ttk.Button(f, text="...", width=3,
                   command=lambda: self.browse("keyfile")).grid(row=4, column=2, padx=3)
        ttk.Button(f, text="...", width=3,
                   command=lambda: self.browse("viewer")).grid(row=7, column=2, padx=3)

        self.btn = ttk.Button(f, text="Connect", command=self.toggle)
        self.btn.grid(row=len(rows), column=0, columnspan=3, pady=8, sticky="ew")
        self.logbox = tk.Text(f, height=10, width=70, state="disabled")
        self.logbox.grid(row=len(rows) + 1, column=0, columnspan=3, sticky="nsew")
        root.protocol("WM_DELETE_WINDOW", self.on_close)

    # ---- helpers ---------------------------------------------------------
    def browse(self, key):
        p = filedialog.askopenfilename()
        if p:
            self.vars[key].set(p)

    def log(self, msg):
        def w():
            self.logbox.configure(state="normal")
            self.logbox.insert("end", msg + "\n")
            self.logbox.see("end")
            self.logbox.configure(state="disabled")
        self.root.after(0, w)

    def confirm(self, msg):
        ev, res = threading.Event(), []
        def ask():
            self.root.deiconify()
            self.root.lift()
            self.root.attributes("-topmost", True)
            res.append(messagebox.askyesno("Confirm", msg, parent=self.root))
            self.root.attributes("-topmost", False)
            ev.set()
        self.root.after(0, ask)
        ev.wait()
        return res[0]

    def save_cfg(self):
        keys = ("host", "port", "user", "keyfile", "rport", "lport", "viewer", "args")
        save_json(CFG_FILE, {k: self.vars[k].get() for k in keys})  # password never saved

    # ---- actions ---------------------------------------------------------
    def toggle(self):
        if self.tunnel:
            self.disconnect()
        else:
            self.btn.configure(state="disabled", text="Connecting ...")
            threading.Thread(target=self.connect, daemon=True).start()

    def connect(self):
        v = {k: x.get().strip() for k, x in self.vars.items()}
        v["password"] = self.vars["password"].get()
        t = Tunnel(self.log, self.confirm)
        try:
            host, port = v["host"], int(v["port"] or 22)
            rport = int(v["rport"] or 5900)
            t.pin_key = f"{host}:{port}->{rport}"
            t.connect_ssh(host, port, v["user"], v["password"], v["keyfile"], v["password"])
            t.probe(rport)
            lport = t.start_proxy(rport, int(v["lport"] or 0))
        except Exception as e:
            self.log(f"ERROR: {e!r}")
            t.stop()
            self.root.after(0, lambda: self.btn.configure(state="normal", text="Connect"))
            return
        self.tunnel = t
        self.save_cfg()
        self.log(f"Tunnel ready: 127.0.0.1:{lport}")
        if v["viewer"]:
            try:
                args = v["args"].replace("{port}", str(lport)).split()
                self.viewer_proc = subprocess.Popen([v["viewer"], *args])
                threading.Thread(target=self.watch_viewer, daemon=True).start()
            except Exception as e:
                self.log(f"Could not start viewer: {e}")
        else:
            self.log(f"No viewer set - point any VNC viewer at 127.0.0.1:{lport}")
        self.root.after(0, lambda: self.btn.configure(state="normal", text="Disconnect"))

    def watch_viewer(self):
        proc = self.viewer_proc
        if proc:
            proc.wait()
            self.log("Viewer closed - tearing down tunnel.")
            self.root.after(0, self.disconnect)

    def disconnect(self):
        if self.tunnel:
            self.tunnel.stop()
            self.tunnel = None
        self.viewer_proc = None
        self.btn.configure(state="normal", text="Connect")
        self.log("Disconnected.")

    def on_close(self):
        self.disconnect()
        self.root.destroy()


if __name__ == "__main__":
    root = tk.Tk()
    App(root)
    root.mainloop()